/**
 * Sector + ContentType specific fields for create form and display.
 * Each industry sector has different marketing data & display needs.
 */

export type FieldKind =
  | 'text'
  | 'number'
  | 'currency'
  | 'select'
  | 'multiline'
  | 'url'
  | 'images'
  | 'date';

export interface SectorField {
  key: string;
  kind: FieldKind;
  labelEn: string;
  labelId: string;
  placeholderEn?: string;
  placeholderId?: string;
  hintEn?: string;
  hintId?: string;
  required?: boolean;
  options?: { value: string; labelEn: string; labelId: string }[];
  /** Show in create form */
  inCreate: boolean;
  /** Show in card/list preview */
  inCard: boolean;
  /** Show in detail view */
  inDetail: boolean;
}

/** Fields that need images (gallery/carousel) - typically product, service, property, retail */
export const IMAGE_HEAVY_TYPES = [
  'product',
  'service',
  'property',
  'company',
  'tool_rental',
  'business_transfer',
] as const;
export const IMAGE_HEAVY_SECTORS = [
  'retail',
  'realestate',
  'automotive',
  'hospitality',
  'textiles',
  'food',
] as const;

export function needsImageGallery(type: string, sector?: string): boolean {
  if (IMAGE_HEAVY_TYPES.includes(type as (typeof IMAGE_HEAVY_TYPES)[number]))
    return true;
  if (
    sector &&
    IMAGE_HEAVY_SECTORS.includes(sector as (typeof IMAGE_HEAVY_SECTORS)[number])
  )
    return true;
  return false;
}

